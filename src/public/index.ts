/**
 * Точка входа `./public` — режим «Лендинг без бэкенда».
 *
 * Лендинг — статическая страница без серверной части: секрета клиента ему
 * держать негде, и закрытая операция установки ему недоступна. Состав рейла
 * он получает публичной операцией `GET /api/public/navigation` прямо
 * из браузера (PRD навигации 5.8); операция включается развёртыванием
 * установки.
 *
 * **Компоненты берутся из входа `.`** — те же `CrossServiceRail`,
 * `CrossServiceMenu`, `CrossServiceBar`, что у продукта установки. Второго
 * комплекта нет: копия разошлась бы с эталоном на первой правке. Отсюда
 * приходят только данные для них; `UserMenu` и шестерёнка в этом режиме
 * не нужны — пользователь не входит.
 *
 * **Единственный вход пакета, которому разрешён сетевой запрос.** Компоненты
 * по-прежнему получают данные только props: запрос живёт в адаптере, как
 * знание о `usePage()` живёт в `./inertia`. Хранилищ, консоли и зашитых
 * адресов здесь нет — это проверяет условие 11 `check:isolation`.
 *
 * Зависимость ровно одна — `vue`. Разборщик ответа и загрузчик наружу
 * не отдаются: это устройство входа, и их сигнатуры не должны становиться
 * публичным контрактом.
 */

