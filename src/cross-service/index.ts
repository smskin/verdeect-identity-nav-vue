/**
 * Точка входа переносимого каталога кросс-сервисной навигации
 * (PRD навигации 9.1).
 *
 * Продукт ввозит компоненты и типы отсюда, а не из отдельных файлов:
 * это точка входа `.` npm-пакета, и раскладка файлов внутри каталога
 * на импорты продукта не влияет.
 *
 * **Правила каталога.** Внутри нет ни сетевых обращений, ни браузерных
 * хранилищ, ни импортов из приложения, ни компонентов PrimeVue, ни адресов
 * сервиса и токенов. Допустимы `vue` и собственные файлы каталога.
 * Проверяется `scripts/check-component-isolation.mjs`.
 *
 * **Шрифта иконок каталог не требует.** Прежде классы `pi pi-*` были здесь
 * оговорённым исключением, и продукт обязан был подключить PrimeIcons; теперь
 * иконки пунктов приходят файлами по `NavItem.iconUrl`, а значки блока
 * пользователя встроены в `UserMenu.vue`. Заводить зависимость от шрифта
 * заново не следует: подключать его пришлось бы каждому продукту установки.
 *
 * **Три вида навигации, и продукт выбирает два из них.**
 *   - `CrossServiceRail` — постоянная полоса слева; десктоп.
 *   - `CrossServiceMenu` — блок внутри выдвижного меню продукта;
 *     мобильный вид 1.
 *   - `CrossServiceBar` — плашка внизу экрана; мобильный вид 2.
 *
 * Мобильные виды **взаимоисключающие**: монтируются полоса и один из двух.
 * Плашка внизу подходит не всякой оболочке, поэтому выбор оставлен продукту,
 * а не навязан пакетом. Общий компонент с пропом `placement` разделён именно
 * поэтому: он требовал `logoUrl` у всех трёх видов, показывая логотип в одном,
 * и не мешал смонтировать полосу внутрь выдвижного меню.
 *
 * **Числовых порогов ширины здесь нет — и заводить их нельзя.** Порог
 * узкого экрана принадлежит хозяину: он обязан совпадать с порогом
 * навигации продукта, а у рейла собственного мобильного режима нет
 * (PRD навигации 7.1). Каждый вид проставляет на корневом элементе
 * `data-placement`, а какой из них показать, решает таблица стилей продукта
 * своими медиазапросами. В интерфейсе
 * сервиса это `resources/css/app.css`, где порог оболочки Sakai уже задан.
 * Константа «чтобы не забыть значение», заведённая здесь, уехала бы вместе
 * с пакетом в продукт с другим порогом.
 */

