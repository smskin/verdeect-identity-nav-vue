/**
 * Типы переносимого каталога кросс-сервисной навигации
 * (PRD навигации 9.1–9.3).
 *
 * Каталог рассчитан на выемку в отдельный репозиторий перемещением файлов,
 * поэтому здесь нет ни одного импорта из приложения: ни `@/types`,
 * ни `@inertiajs/*`. Состав полей `NavItem` совпадает с ответом операции
 * `POST /api/users/services` (PRD навигации 5.3, `RSNavigationItem`) —
 * продукт передаёт `items` ответа как есть, ничего не перекладывая.
 *
 * Индексных сигнатур здесь нет намеренно — по тому же доводу, что
 * и в `resources/js/types/registry.ts`: она заглушила бы обращение
 * к несуществующему полю, и расхождение сервера с компонентом стало бы
 * необнаруживаемым.
 *
 * Числовых порогов ширины в каталоге нет — см. докблок `index.ts`.
 */

/**
 * Значение атрибута `data-placement` на корневом узле каждого вида.
 *
 * **Проп это больше не проп.** Вид задаётся выбранным компонентом, а атрибут
 * остаётся: таблицы стилей продуктов переключают виды по нему, целясь
 * в `[data-placement='rail']` и `[data-placement='overlay']`. Значения
 * сохранены прежними намеренно — переименование потребовало бы правки
 * чужого CSS без единой выгоды.
 */
export type NavPlacement = 'rail' | 'overlay' | 'bottom';

/**
 * Пункт кросс-сервисной навигации (PRD навигации 5.3).
 *
 * Поле названо `name` в единственном числе и является объектом по языкам:
 * это одно имя пункта, отданное на всех поддерживаемых языках сразу.
 * Выбор языка выполняет компонент по prop `locale` (PRD навигации 4.3).
 *
 * `order` — порядок показа; сервер отдаёт пункты уже упорядоченными,
 * но поле оставлено, потому что продукт вправе хранить ответ и склеивать
 * его с собственными данными.
 */
export interface NavItem {
    readonly id: string;
    readonly name: Readonly<Record<string, string>>;
    readonly url: string;
    /**
     * Подписанная ссылка ограниченного срока на файл иконки (SVG).
     *
     * Набора иконок больше нет: шрифт пришлось бы подключать в каждом продукте
     * установки, а продукты о нём не знают и подключать не обязаны. Файл
     * загружает администратор установки, хранилище приватно, постоянного
     * адреса у файла не существует.
     *
     * Пустая строка законна и означает, что ссылки не пришло: так разборщик
     * парной библиотеки читает ответ установки, ещё не перешедшей на
     * загружаемые иконки. Компонент показывает такой пункт первой буквой
     * имени — тем же правилом, что и не загрузившуюся иконку.
     */
    readonly iconUrl: string;
    readonly order: number;
}

/**
 * Пункт меню самого продукта в блоке пользователя (PRD навигации 9.3).
 *
 * Сервис о таких пунктах не знает и их не хранит: их передаёт продукт,
 * встраивающий компонент.
 */
export interface ProductMenuItem {
    readonly name: string;
    readonly url: string;
}

/**
 * Общие props трёх видов навигации.
 *
 * Состав пунктов, язык и адрес открытой страницы нужны каждому; различаются
 * виды тем, что добавляют сверх этого.
 */
interface NavProps {
    readonly items: readonly NavItem[];
    readonly locale: string;
    /**
     * Абсолютный адрес открытой страницы.
     *
     * Необязателен, но передавать его следует: без него компонент берёт адрес
     * сам при монтировании, а правило подсветки сравнивает схему и хост —
     * относительный путь не подсветит ничего.
     */
    readonly currentUrl?: string;
    /**
     * Адрес страницы профиля в установке — им открывается шестерёнка настроек.
     *
     * **Признак входа выражен адресом, а не отдельным полем.** Гостю установка
     * адреса профиля не отдаёт, поэтому пустое значение и есть «смотрит гость»:
     * шестерёнка не рисуется. Отдельный `authed` завёл бы второй источник
     * истины о том же и разошёлся бы с первым.
     *
     * Необязателен: продукт, оставшийся на прежней версии, его не передаёт
     * и получает прежнее поведение — без шестерёнки.
     */
    readonly profileUrl?: string;
}

/**
 * Props `CrossServiceRail` — постоянной полосы слева (PRD навигации 7.1).
 *
 * `logoUrl` требуется **только здесь**: логотип установки рисует полоса,
 * и прежний общий компонент требовал его у всех трёх видов, показывая
 * в одном.
 */
export interface CrossServiceRailProps extends NavProps {
    readonly logoUrl: string;
    /**
     * Высота плитки логотипа — любая длина CSS (`'4rem'`, `'64px'`).
     *
     * Существует ради **совмещения с шапкой продукта**: у большинства оболочек
     * сверху есть полоса, и плитка, кончающаяся вровень с ней, читается как
     * часть общей рамки, а не как случайный квадрат. Высота приходит пропом,
     * а не переменной оформления, потому что принадлежит **оболочке**: пакет
     * о существовании шапки не знает, а у продукта без неё её и нет.
     *
     * Не задана — плитка квадратная по ширине полосы. Это и есть случай
     * оболочки без шапки: квадрат ни с чем не совмещается и ничего
     * не обещает.
     */
    readonly logoHeight?: string;
}

/**
 * Props `CrossServiceMenu` — блока внутри выдвижного меню продукта.
 *
 * Ширину задаёт панель хозяина, поэтому геометрии здесь нет. Разделы самого
 * продукта рисуются **после** этого блока: шов — `cross-service-nav__divider`.
 */
export type CrossServiceMenuProps = NavProps;

/**
 * Как плашка стоит на экране; значение атрибута `data-positioning`
 * на её корневом узле.
 *
 * `fixed` — плашка прижата к нижнему краю окна самим пакетом: правило это
 * одинаково у любого продукта, и повторять его в каждом репозитории незачем.
 * `static` — плашка остаётся в потоке документа там, где смонтирована;
 * оболочка, ставящая её по-своему, берёт это значение.
 *
 * Значения строками, а не признаком: режим виден в разметке и в браузерных
 * сценариях, и добавить третий способ стоять на экране можно, ничего
 * не переименовывая.
 */
export type NavBarPositioning = 'fixed' | 'static';

/**
 * Props `CrossServiceBar` — плашки внизу экрана.
 *
 * Второй мобильный вид, **альтернатива** блоку в меню, а не дополнение к нему:
 * продукт монтирует полосу и один из двух. Бургер и всплывающее меню панели
 * принадлежат продукту — это его меню, как и выдвижная панель.
 */
export interface CrossServiceBarProps extends NavProps {
    /**
     * Положение плашки на экране; умолчание — прижата к нижнему краю.
     *
     * Умолчание именно такое, потому что плашка внизу экрана — это и есть
     * её назначение: продукт, которому нужно иное, скажет об этом явно.
     * Высоту переменной плашка отдаёт в обоих режимах: отступ содержимому
     * нужен оболочке независимо от того, кто плашку закрепил.
     */
    readonly positioning?: NavBarPositioning;
}

/**
 * Props компонента `UserMenu` (PRD навигации 9.3).
 *
 * Все три формы имени приходят готовыми: компонент их не склеивает
 * и не сокращает. `email` без значения означает, что строка адреса
 * не показывается, а не что вместо неё показывается пустая.
 */
export interface UserMenuProps {
    readonly shortName: string;
    readonly name: string;
    readonly initials: string;
    readonly email?: string | null;
    readonly profileUrl: string;
    readonly locale: string;
    readonly items?: readonly ProductMenuItem[];
}
