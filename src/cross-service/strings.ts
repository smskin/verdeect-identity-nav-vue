/**
 * Словарь строк переносимого каталога (PRD навигации 9.1).
 *
 * **Осознанное отступление от правила «отображаемого текста в коде нет»**
 * (`.ai-factory/rules/base.md`), прямо предписанное PRD 9.1: строки
 * компонентов живут внутри компонента по языкам, продукт их не передаёт
 * и не переопределяет. Основания: продукт не обязан вести словарь переводов
 * сервиса; при выемке каталога в пакет словарь переезжает вместе с ним,
 * а файл `lang/` — нет. Отступление ограничено этим каталогом.
 *
 * Требование полноты сохранено: состав ключей совпадает между языками,
 * перечень языков совпадает с перечнем языков интерфейса, и то и другое
 * проверяет `npm run check:strings` (`scripts/check-component-strings.mjs`).
 * Выбор языка и отступление к запасному закреплены набором
 * `tests/strings.spec.ts`.
 *
 * **Формат словаря обязан оставаться плоским.** Проверка при сборке читает
 * этот файл текстом и разбирает строки вида `ключ: 'значение'` внутри блока
 * языка; вложенные объекты она не увидит, и полнота словаря перестанет
 * проверяться молча.
 *
 * **Расширение на третий язык — добавление ключа языка в `STRINGS`** вместе
 * с полным составом строк. Правки компонентов это не требует: язык выбирается
 * значением prop `locale`.
 */

/**
 * Строки по языкам: код языка → ключ строки → значение.
 *
 * Тип объявлен широким намеренно: `translate()` обращается к словарю
 * по значению prop `locale`, то есть по произвольной строке, и словарь
 * с литеральными ключами такому обращению недоступен.
 */
export const STRINGS: Readonly<
    Record<string, Readonly<Record<string, string>>>
> = {
    ru: {
        services: 'Сервисы',
        profile: 'Профиль',
        logout: 'Выход',
        openMenu: 'Открыть меню пользователя',
        logoAlt: 'Логотип установки',
    },
    en: {
        services: 'Services',
        profile: 'Profile',
        logout: 'Sign out',
        openMenu: 'Open the user menu',
        logoAlt: 'Installation logo',
    },
};

/**
 * Язык, к которому отступает компонент при неизвестном `locale`.
 *
 * Первый объявленный, а не пустая строка: пустая подпись в рейле
 * неотличима от отсутствия пункта.
 */
const FALLBACK_LOCALE = Object.keys(STRINGS)[0];

/**
 * Отдаёт строку словаря на заданном языке.
 *
 * **Неизвестный язык — штатный вход, а не поломка.** Прежде язык приходил
 * из `/userinfo` установки и был одним из её языков по построению, поэтому
 * чужое значение означало ошибку встраивания и сопровождалось предупреждением
 * в консоль. Теперь язык гостя определяет продукт — заголовком
 * `Accept-Language`, кукой или умолчанием, — и `de` приходит от исправного
 * продукта на исправной странице. Предупреждать здесь не о чем.
 *
 * **Предупреждение убрано ещё и потому, что было непереносимым.** Оно стояло
 * под `import.meta.env.DEV` — конструкцией, которую подставляет бандлер Vite;
 * вне такой сборки (отрисовка на сервере, другой бандлер) обращение к ней
 * роняло всю ветку неизвестного языка с `TypeError`. Каталог не вправе
 * предполагать, чем собран потребитель: это ровно та переносимость, ради
 * которой он изолирован.
 *
 * Неизвестный ключ возвращается сам собой — тем же приёмом, что
 * `useTranslations.t()`: так его видно на экране, а `npm run check:strings`
 * роняет прогон до того, как он туда попадёт.
 */
export function translate(locale: string, key: string): string {
    const catalog = STRINGS[locale];

    if (catalog === undefined) {
        return STRINGS[FALLBACK_LOCALE][key] ?? key;
    }

    return catalog[key] ?? key;
}
