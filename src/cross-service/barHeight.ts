/**
 * Высота плашки внизу экрана, отданная оболочке продукта переменной оформления.
 *
 * **Зачем это здесь.** Плашка закреплена у нижнего края и из потока документа
 * вынута — содержимое страницы её не замечает и уходит под неё последними
 * строками. Отступ содержимому отводит продукт: какой узел его оболочки
 * прокручивается, пакет не знает и знать не должен. Но **высоту** плашки знает
 * только пакет, и до сих пор продукты записывали её числом — с предсказуемым
 * исходом: в одном 49 px, в другом 48, а в комментарии самого оформления
 * третье значение. Переменная `--cross-service-bar-height` кладёт конец
 * трём источникам одной величины, как `--cross-service-rail-width` положила
 * конец двум источникам ширины полосы.
 *
 * **Почему переменная ставится на корень документа, а не на саму плашку.**
 * Переменная видна только потомкам узла, на котором объявлена, а адресована
 * она чужой оболочке — узлу в другой ветви дерева. Другого общего предка,
 * кроме корня документа, у них нет.
 *
 * **Почему обращение к `document` живёт здесь, а не в компоненте.** Условие 7
 * `scripts/check-component-isolation.mjs` держит перечень мест обращения
 * закреплённым константой. Одно место в перечне вместо второго компонента — и
 * `CrossServiceBar.vue` остаётся свободным от DOM, каким он стал после перехода
 * на загружаемые иконки. Заодно чистая часть — решение «какое значение» —
 * проверяется прямыми вызовами: браузер в наборах пакета не поднимается.
 *
 * **Почему нулевая высота снимает переменную, а не пишет ноль.** Главный случай
 * здесь — не размонтирование, а скрытие: продукт гасит плашку своим
 * медиазапросом на широком экране (`[data-placement='bottom'] { display: none }`),
 * компонент при этом жив, а наблюдатель сообщает нулевой размер. Снятая
 * переменная возвращает продукту его запасное значение
 * (`var(--cross-service-bar-height, 0px)`), и ноль получается **измерением**,
 * а не знанием о чужом пороге, которого у пакета нет.
 *
 * **Почему счётчик.** Плашек на странице может оказаться две — перемонтирование
 * макета продуктом, две оболочки рядом. Переменная одна, и снимать её вправе
 * только последняя освободившая: иначе ушедшая плашка погасила бы высоту
 * у оставшейся, и отступ исчез бы под живой плашкой.
 *
 * Сторожевых условий на отсутствие `document` здесь нет намеренно: занимают
 * и освобождают место хуки жизненного цикла компонента, а на сервере они
 * не выполняются.
 */

/**
 * Имя переменной оформления. Объявлено здесь единственный раз: повторённое
 * в таблице стилей, оно разошлось бы с этим местом при первой же правке.
 */
const BAR_HEIGHT_VARIABLE = '--cross-service-bar-height';

/** Сколько плашек сейчас занимают место на экране. */
let occupied = 0;

/** Последняя измеренная высота плашки в пикселях. */
let measured = 0;

/**
 * Значение переменной по числу занявших плашек и измеренной высоте либо `null`,
 * когда переменную следует снять.
 *
 * Округление **вверх**: дробную высоту дают масштабирование страницы и
 * безопасная зона устройства, а отступ, округлённый вниз, короче плашки —
 * и последняя строка содержимого прячется под ней краем.
 */
export function barHeightValue(
    occupiedBars: number,
    height: number,
): string | null {
    if (occupiedBars <= 0) {
        return null;
    }

    if (!Number.isFinite(height) || height <= 0) {
        return null;
    }

    return `${Math.ceil(height)}px`;
}

/** Применяет текущее решение к корню документа. */
function apply(): void {
    const value = barHeightValue(occupied, measured);
    const root = document.documentElement;

    if (value === null) {
        root.style.removeProperty(BAR_HEIGHT_VARIABLE);

        return;
    }

    root.style.setProperty(BAR_HEIGHT_VARIABLE, value);
}

/** Плашка смонтирована и занимает место у нижнего края. */
export function occupyBarHeight(): void {
    occupied += 1;

    apply();
}

/**
 * Плашка размонтирована. Переменная снимается, только когда освободилась
 * последняя: до тех пор высоту держит оставшаяся.
 */
export function releaseBarHeight(): void {
    occupied = Math.max(0, occupied - 1);

    apply();
}

/**
 * Измеренная высота плашки изменилась.
 *
 * Ноль означает скрытую плашку, а не ошибку измерения: так выглядит узел,
 * погашенный медиазапросом продукта.
 */
export function reportBarHeight(height: number): void {
    measured = height;

    apply();
}
