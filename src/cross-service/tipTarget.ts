import type { InjectionKey, Ref } from 'vue';

/**
 * Узел, в который `NavTip` выносит подсказку полосы вместо `body`.
 *
 * **Существует ради пользовательского элемента `./element`.** Его визуальный
 * слой живёт в теневом корне, и подсказка, вынесенная в `body`, остаётся без
 * оформления и без тёмной палитры хоста: стили теневого корня на узел
 * в документе не действуют. Элемент отдаёт слой внутри своего теневого корня,
 * рядом с полосой, а не в ней, — прокручиваемая полоса обрезала бы подсказку.
 *
 * **Отдаётся узел, а не селектор.** Строку `Teleport` разрешает в документе,
 * и в теневой корень селектор не дотянется.
 *
 * Без отданного узла — или пока слой не смонтирован — подсказка уезжает
 * в `body`, как у продуктов на Vue, где стили пакета глобальные.
 */
export const NAV_TIP_TARGET: InjectionKey<Readonly<Ref<HTMLElement | null>>> = Symbol(
    'cross-service-nav-tip-target',
);
