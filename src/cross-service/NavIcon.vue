<script setup lang="ts">
import { computed } from 'vue';

/**
 * Иконка пункта либо заглушка первой буквой (PRD навигации 9.4).
 *
 * Внутренний узел каталога: во вход `.` не отдаётся, продукт его не монтирует.
 * Существует ради того, чтобы три вида навигации рисовали иконку **одним**
 * кодом — скопированная трижды, она разошлась бы первой.
 *
 * **Файл по подписанной ссылке, а не глиф шрифта.** Набора иконок нет: шрифт
 * пришлось бы подключать в каждом продукте установки, а продукты о нём не знают.
 *
 * **Файл рисуется маской, а не изображением** (PRD навигации 9.4). Причина —
 * цвет: внешнее изображение не наследует цвет страницы, и `currentColor` внутри
 * загруженного SVG разрешается в его собственном пустом контексте, то есть
 * в чёрный. Пункты выходили чёрными вместо серых, а текущий не окрашивался
 * акцентом вовсе. Маска берёт из файла **силуэт**, а заливку — из `currentColor`
 * самой ссылки, поэтому цвет состояний задаёт таблица стилей, как в макете.
 *
 * Цена — иконка одноцветна: многоцветный знак превратится в силуэт. Условие
 * возврата к вопросу названо в разделе 12 PRD и выполнено — установки заводят
 * линейные значки одного тона.
 *
 * **Скрытая картинка рядом — не дубль, а единственный способ узнать
 * о неудаче.** У маски события `error` не бывает: она свойство оформления,
 * а не узел. Без картинки запасной путь «иконка не загрузилась — первая буква»
 * (критерий Н-36) перестал бы срабатывать молча. Адрес у обоих один, и браузер
 * забирает его из кэша — второго обращения к хранилищу не возникает.
 *
 * **`crossorigin` у картинки обязателен, и ровно из-за общего кэша.** Маску
 * браузер загружает запросом CORS: шлёт `Origin` и ждёт в ответе разрешения.
 * Картинка без этого атрибута идёт запросом без `Origin`, а хранилище
 * S3 отдаёт заголовки CORS **только** спрошенному с `Origin` и не ставит
 * `Vary: Origin`. Запись кэша на оба запроса одна, и ответ без разрешения,
 * попавший в неё первым, достаётся и маске: маска не применяется, а узел,
 * замаскированный пустотой, **исчезает целиком** — ни иконки, ни заглушки.
 * Какой из двух запросов придёт первым, не определено, поэтому иконки
 * пропадали у части пользователей и возвращались лишь со сбросом кэша.
 *
 * Атрибут уравнивает режимы: оба запроса шлют `Origin`, в кэше лежит ответ
 * с разрешением. Попутно он делает запасной путь честным — на хранилище
 * без настроенного CORS картинка теперь даёт `error` и заглушку первой буквой
 * вместо пустого места. Отсюда обязанность установки: бакет иконок обязан
 * отдавать `Access-Control-Allow-Origin` (`docs/checklist.md`).
 *
 * **Пустой `iconUrl` равнозначен неудачной загрузке.** Так парная библиотека
 * читает ответ установки, ещё не перешедшей на загружаемые иконки.
 */
interface Props {
    /** Подписанная ссылка на файл иконки; пустая — ссылки не пришло. */
    readonly url: string;
    /** Идентификатор пункта — им помечается узел для сценариев продукта. */
    readonly itemId: string;
    /** Показывать заглушку вместо изображения. */
    readonly stubbed: boolean;
    /** Первая буква имени — содержимое заглушки. */
    readonly initial: string;
}

const props = defineProps<Props>();

const emit = defineEmits<{ error: [] }>();

/**
 * Адрес файла в виде значения CSS для маски.
 *
 * Собирается в скрипте, а не в разметке: в выражении шаблона кавычки пришлось
 * бы записывать сущностями, и приём этот читается хуже, чем работает.
 * Подписанная ссылка приходит закодированной, кавычек в ней не бывает.
 */
const mask = computed<string>(() => `url('${props.url}')`);
</script>

<template>
    <span v-if="stubbed" class="cross-service-nav__stub" aria-hidden="true">{{
        initial
    }}</span>
    <span
        v-else
        class="cross-service-nav__icon"
        :style="{ '--cross-service-icon': mask }"
        aria-hidden="true"
        :data-icon-for="itemId"
    >
        <img
            class="cross-service-nav__probe"
            :src="url"
            crossorigin="anonymous"
            alt=""
            aria-hidden="true"
            @error="emit('error')"
        />
    </span>
</template>
