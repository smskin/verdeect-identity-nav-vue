<script setup lang="ts">
import { computed, onBeforeUnmount, onMounted, ref, watch } from 'vue';
import { loadIcon } from './iconSource';

/**
 * Иконка пункта либо заглушка первой буквой (PRD навигации 9.4).
 *
 * Внутренний узел каталога: во вход `.` не отдаётся, продукт его не монтирует.
 * Существует ради того, чтобы три вида навигации рисовали иконку **одним**
 * кодом — скопированная трижды, она разошлась бы первой.
 *
 * **Файл по подписанной ссылке, а не глиф шрифта.** Набора иконок нет: шрифт
 * пришлось бы подключать в каждом продукте установки, а продукты о нём не знают.
 *
 * **Файл рисуется маской, а не изображением** (PRD навигации 9.4). Причина —
 * цвет: внешнее изображение не наследует цвет страницы, и `currentColor` внутри
 * загруженного SVG разрешается в его собственном пустом контексте, то есть
 * в чёрный. Пункты выходили чёрными вместо серых, а текущий не окрашивался
 * акцентом вовсе. Маска берёт из файла **силуэт**, а заливку — из `currentColor`
 * самой ссылки, поэтому цвет состояний задаёт таблица стилей, как в макете.
 *
 * Цена — иконка одноцветна: многоцветный знак превратится в силуэт. Условие
 * возврата к вопросу названо в разделе 12 PRD и выполнено — установки заводят
 * линейные значки одного тона.
 *
 * **Маска получает содержимое файла адресом `data:`, а не адрес хранилища.**
 * Файл забирает `iconSource.ts` одним запросом CORS; почему маске нельзя
 * отдавать подписанную ссылку — там же. Коротко: Safari грузит маску без
 * `Origin`, ответ без разрешения CORS ложился в общий кэш, и картинки с тем же
 * адресом падали проверкой CORS — иконки пропадали «время от времени».
 *
 * **Скрытая картинка рядом — проверка, что `data:` допущен политикой
 * содержимого.** У маски события `error` не бывает: она свойство оформления,
 * а не узел. Без `data:` в `img-src` продукта маска не применится молча,
 * и узел, замаскированный пустотой, исчезнет целиком — ни иконки, ни заглушки.
 * Картинка с тем же адресом `data:` подчиняется той же директиве и сообщает
 * об отказе событием `error` — пункт переходит на букву (критерий Н-36).
 * В хранилище картинка не ходит: содержимое уже в адресе.
 *
 * **Пустой `iconUrl` равнозначен неудачной загрузке.** Так парная библиотека
 * читает ответ установки, ещё не перешедшей на загружаемые иконки.
 *
 * **Неудача загрузки — не с первой ошибки: файл запрашивается ещё дважды.**
 * Кратковременный сбой хранилища (обрыв соединения, 5xx, таймаут первого
 * запроса) штатен и проходит сам, а буква держалась бы до смены состава
 * пунктов, в SPA без перемонтирования — до перезагрузки. Повторы идут в обход
 * кэша обозревателя. Отказ картинки `data:` не повторяется: его причина —
 * политика содержимого либо испорченный файл, и повтор дал бы тот же исход.
 *
 * **Загрузка начинается при монтировании, а не в `setup`.** При отрисовке
 * на сервере запроса быть не должно — там его результат некому показать.
 *
 * **Маска ставится только после загрузки картинки.** До неё маска — прозрачный
 * градиент, а не `none`: без маски узел закрашен `currentColor` целиком
 * и показывал бы залитый квадрат на месте иконки.
 */
interface Props {
    /** Подписанная ссылка на файл иконки; пустая — ссылки не пришло. */
    readonly url: string;
    /** Идентификатор пункта — им помечается узел для сценариев продукта. */
    readonly itemId: string;
    /** Показывать заглушку вместо изображения. */
    readonly stubbed: boolean;
    /** Первая буква имени — содержимое заглушки. */
    readonly initial: string;
}

const props = defineProps<Props>();

const emit = defineEmits<{ error: [] }>();

/** Маска до загрузки картинки — полностью прозрачная. */
const TRANSPARENT_MASK = 'linear-gradient(transparent, transparent)';

/**
 * Задержки повторных загрузок, мс. Длина перечня — число повторов.
 *
 * Первая короткая — на обрыв соединения, вторая длиннее — на перегрузку
 * хранилища. Дольше ждать незачем: пункт без силуэта заметнее буквы.
 */
const RETRY_DELAYS = [500, 2000];

/** Содержимое файла адресом `data:`; пустое — ещё не загружено. */
const source = ref('');

const loaded = ref(false);

/**
 * Адрес файла в виде значения CSS для маски.
 *
 * Собирается в скрипте, а не в разметке: в выражении шаблона кавычки пришлось
 * бы записывать сущностями. В base64 кавычек не бывает.
 */
const mask = computed<string>(() =>
    loaded.value ? `url('${source.value}')` : TRANSPARENT_MASK,
);

/** Номер попытки: повторы, в отличие от первой, идут в обход кэша. */
let attempt = 0;

/**
 * Поколение загрузки. Ответ, пришедший после смены ссылки, относится
 * к прежнему файлу и отбрасывается.
 */
let generation = 0;

let retryTimer: ReturnType<typeof setTimeout> | null = null;

const clearRetry = (): void => {
    if (retryTimer !== null) {
        clearTimeout(retryTimer);
        retryTimer = null;
    }
};

const load = (): void => {
    if (props.stubbed || props.url === '') {
        return;
    }

    const current = generation;

    loadIcon(props.url, attempt > 0).then(
        (content) => {
            if (current === generation) {
                source.value = content;
            }
        },
        () => {
            if (current === generation) {
                retry();
            }
        },
    );
};

const retry = (): void => {
    const delay = RETRY_DELAYS[attempt];

    if (delay === undefined) {
        emit('error');

        return;
    }

    clearRetry();
    retryTimer = setTimeout(() => {
        retryTimer = null;
        attempt += 1;
        load();
    }, delay);
};

/** Начать историю попыток заново: прежние неудачи относились к старой ссылке. */
const restart = (): void => {
    clearRetry();
    generation += 1;
    attempt = 0;
    source.value = '';
    loaded.value = false;
    load();
};

const onLoad = (): void => {
    loaded.value = true;
};

const onRejected = (): void => {
    emit('error');
};

onMounted(load);

// Снятие заглушки при той же ссылке — тоже повод загрузить: новый состав
// пунктов сбрасывает неудачи, а адреса в нём могут совпасть с прежними.
watch([() => props.url, () => props.stubbed], restart);

onBeforeUnmount(() => {
    clearRetry();
    generation += 1;
});
</script>

<template>
    <span v-if="stubbed" class="cross-service-nav__stub" aria-hidden="true">{{
        initial
    }}</span>
    <span
        v-else
        class="cross-service-nav__icon"
        :style="{ '--cross-service-icon': mask }"
        aria-hidden="true"
        :data-icon-for="itemId"
    >
        <img
            v-if="source !== ''"
            class="cross-service-nav__probe"
            :src="source"
            alt=""
            aria-hidden="true"
            @load="onLoad"
            @error="onRejected"
        />
    </span>
</template>
