/**
 * Правило текущего пункта рейла (PRD навигации 7.3).
 *
 * Вынесено из компонента отдельным файлом намеренно: правило нужно и читать,
 * и проверять прямыми вызовами, а внутри `.vue` оно недоступно ни тому,
 * ни другому.
 *
 * Продукт правило не реализует и не сообщает компоненту, «кто он»:
 * идентификатор пункта у каждой установки свой, и хранить его в конфигурации
 * продукта нельзя.
 *
 * Функция чистая: ни `window`, ни `document` здесь нет — адрес открытой
 * страницы подставляет компонент.
 */

import type { NavItem } from './types';

/**
 * Путь без завершающего `/`.
 *
 * Корень (`/`) и пустой путь становятся пустой строкой: пункт, указывающий
 * на корень установки, совпадает с любой её страницей.
 */
function normalizePath(path: string): string {
    return path.endsWith('/') ? path.slice(0, -1) : path;
}

/**
 * Находится ли страница «под» адресом пункта.
 *
 * Сравнение посегментное, а не построчное: пункт `/user` не является
 * текущим на странице `/users/01K`.
 */
function covers(itemPath: string, pagePath: string): boolean {
    if (itemPath === '') {
        return true;
    }

    return pagePath === itemPath || pagePath.startsWith(`${itemPath}/`);
}

/** Разбирает адрес; непригодный отдаёт `null`, а не бросает отказ. */
function parse(url: string): URL | null {
    try {
        return new URL(url);
    } catch {
        return null;
    }
}

/**
 * Идентификатор пункта, под адресом которого находится открытая страница.
 *
 * Правило двухъярусное.
 *
 * **Ярус первый — по пути.** При нескольких совпадениях выбирается пункт
 * с самым длинным путём; при равной длине — первый в переданном порядке,
 * потому что порядок задан реестром и он же задаёт предпочтение.
 *
 * **Ярус второй — по хосту, запасной.** Если по пути не совпал никто,
 * текущим становится **первый по порядку** пункт с тем же хостом. Довод:
 * пока человек находится на домене сервиса, рейл обязан показывать, где
 * человек находится. Раздел этого сервиса, на который пункта нет, — случай
 * обычный (пункт «Пользователи» и открытые «Настройки»), и гасить подсветку
 * в нём значило бы сообщать, что человек ушёл с сервиса, чего не произошло.
 *
 * Отсюда оба наблюдаемых поведения: единственная ссылка на домен горит везде
 * на нём, а при нескольких ссылках на один домен точное совпадение пути
 * побеждает запасное, и лишь в разделе, которого нет в реестре, загорается
 * первый пункт этого домена.
 *
 * **Схема и хост обязательны на обоих ярусах.** Запасной ярус смягчает
 * требование к пути, а не к адресу: чужой хост, чужая схема и другой порт
 * не подсвечивают ничего.
 *
 * Строка запроса и якорь в сравнении не участвуют: пункт знает свой адрес
 * и ничего не знает об отборе на странице.
 *
 * Непригодный адрес — страницы либо пункта — не отказ: пункт пропускается,
 * рейл продолжает работать. Одна кривая запись реестра не должна гасить
 * навигацию по всей установке.
 */
export function currentItemId(
    items: readonly NavItem[],
    currentUrl: string,
): string | null {
    const page = parse(currentUrl);

    if (page === null) {
        return null;
    }

    const pagePath = normalizePath(page.pathname);
    let currentId: string | null = null;
    let currentLength = -1;

    /** Первый пункт того же хоста — запасной ответ второго яруса. */
    let sameHostId: string | null = null;

    for (const item of items) {
        const target = parse(item.url);

        if (target === null) {
            continue;
        }

        if (target.protocol.toLowerCase() !== page.protocol.toLowerCase()) {
            continue;
        }

        /* `URL.host` включает порт, и это верно: разные порты — разные установки. */
        if (target.host.toLowerCase() !== page.host.toLowerCase()) {
            continue;
        }

        if (sameHostId === null) {
            sameHostId = item.id;
        }

        const itemPath = normalizePath(target.pathname);

        if (!covers(itemPath, pagePath)) {
            continue;
        }

        if (itemPath.length > currentLength) {
            currentId = item.id;
            currentLength = itemPath.length;
        }
    }

    return currentId ?? sameHostId;
}
