import type { NavItem } from '../cross-service';

/**
 * Профиль вошедшего сотрудника.
 *
 * Приходит от продукта, который получил его с собственного бэкенда.
 * **Токенов здесь нет** и быть не может: схема Backend-for-Frontend
 * обязательна, они живут только на сервере.
 */
export interface IdentityProfile {
    readonly sub: string;
    readonly name: string;
    readonly givenName: string;
    readonly familyName: string;
    readonly middleName: string;
    readonly locale: string;
    readonly shortName: string;
    readonly initials: string;
    /**
     * Адрес владельца учётной записи.
     *
     * Поле обязательное, а пустая строка законна и означает «адреса нет»:
     * установка, которой не разрешена область `email`, утверждения
     * не отдаёт. Необязательное поле заставило бы каждого потребителя
     * различать «не пришло» и «пусто», хотя показывать в обоих случаях
     * нечего — `UserMenu` на пустое значение строку адреса не рисует.
     */
    readonly email: string;
}

/**
 * Данные рейла кросс-сервисной навигации.
 *
 * Пункты приходят уже отфильтрованными по роли и в порядке отображения:
 * своих правил видимости продукт не применяет.
 */
export interface CrossServiceData {
    readonly items: readonly NavItem[];
    /**
     * Адрес страницы профиля в установке.
     *
     * Поле обязательное, а **пустая строка законна и означает «страницы
     * профиля у смотрящего нет»**: гостевой ответ установки поля
     * `profile_url` не содержит вовсе, и парная библиотека приводит его
     * к пустой строке. Так гостевой случай доходит до каталога без
     * вариативной формы, которую каждый потребитель различал бы сам.
     *
     * **Договор несущий, но не всюду.** По нему рейл решает, показывать ли
     * шестерёнку настроек: у гостя адреса нет — шестерёнки нет. А вот
     * `UserMenu` пустое значение пока не сторожит: `email` там закрыт
     * `v-if`, тогда как `profileUrl` подставляется в `href` безусловно,
     * и пустая строка дала бы ссылку на текущую страницу. Сегодня это
     * недостижимо — блок пользователя продукт рисует только при наличии
     * профиля, а вместе с профилем приходит и адрес. Различие записано
     * здесь, чтобы договор не прочитался как уже действующий всюду.
     */
    readonly profileUrl: string;
    readonly logoUrl: string;
}

/**
 * Состав свойств identity, который продукт получает с бэкенда.
 *
 * Как именно продукт их доставляет — разделяемыми свойствами Inertia,
 * начальным состоянием страницы или запросом — пакета не касается:
 * ядро принимает готовое значение.
 */
export interface IdentityProps {
    readonly profile: IdentityProfile | null;
    readonly crossService: CrossServiceData;
    /**
     * Язык интерфейса, определённый **продуктом**.
     *
     * Язык вошедшего принадлежит его учётной записи и приходит в профиле;
     * язык **гостя** установка не знает вовсе — о госте ей ничего
     * не известно. Его определяет продукт: заголовком `Accept-Language`,
     * кукой или собственным умолчанием.
     *
     * Поле необязательно намеренно: продукт, оставшийся на прежней версии
     * парной библиотеки, его не шлёт, и отсутствие обязано вести себя
     * ровно как прежде — язык профиля, иначе запасной.
     *
     * Значением ожидается язык установки (`ru` либо `en`): неизвестный
     * компонент отдаёт запасным, и приведение произвольного значения
     * заголовка к языку установки — обязанность продукта.
     */
    readonly locale?: string;
}
