import { defineConfig } from '@playwright/test';

/**
 * Прогонщик наборов пакета.
 *
 * Браузер не поднимается ни одним набором: `@playwright/test` используется
 * как прогонщик Node со своим `expect`. Правило подсветки текущего пункта
 * проверяется прямыми вызовами — случаи с чужой схемой, чужим портом
 * и непригодным адресом в браузере невоспроизводимы.
 *
 * Отдельного прогонщика ради этого не заводится: Playwright уже нужен входу
 * `./playwright`, который пакет отдаёт продуктам установки.
 */
export default defineConfig({
    testDir: 'tests',
    fullyParallel: true,

    /*
     * На конвейере — репортёр `github`: прогон идёт в GitHub Actions
     * (`.github/workflows/publish.yml`), и он размечает падения аннотациями
     * прямо в задании и в разборе изменений. Файлового отчёта здесь не нужно:
     * читать JUnit XML в GitHub Actions некому — это формат для конвейеров,
     * которые разбирают его сами.
     */
    reporter: process.env.CI ? 'github' : 'list',
});
