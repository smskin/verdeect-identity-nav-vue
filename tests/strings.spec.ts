import { expect, test } from '@playwright/test';
import { STRINGS, translate } from '../src/cross-service/strings';

/**
 * Выбор языка подписей — прямыми вызовами.
 *
 * **Чего не проверяет `check:strings`.** Проверка при сборке читает словарь
 * текстом и стережёт его полноту: состав ключей совпадает между языками,
 * перечень языков совпадает с языками установки. Что `translate()` отдаёт
 * на конкретном языке и как отступает на неизвестном — она не смотрит.
 *
 * **Почему это стало важно.** До гостевого случая язык приходил из профиля,
 * то есть из `/userinfo` установки, и был одним из её языков по построению.
 * Теперь язык присылает продукт, определив его по заголовку `Accept-Language`
 * или куке, — и значением может оказаться что угодно.
 */
test('разрешённый язык доходит до словаря', () => {
    expect(translate('en', 'services')).toBe('Services');
    expect(translate('ru', 'services')).toBe('Сервисы');
});

test('подпись шестерёнки объявлена на обоих языках', () => {
    // Ключ отдельный от `profile`: «Профиль» живёт в блоке пользователя,
    // а шестерёнка рейла ведёт в настройки установки.
    expect(translate('ru', 'settings')).toBe('Настройки');
    expect(translate('en', 'settings')).toBe('Settings');
});

test('неизвестный язык отступает к первому объявленному', () => {
    const fallback = Object.keys(STRINGS)[0];

    expect(translate('de', 'services')).toBe(STRINGS[fallback].services);
});

test('неизвестный ключ возвращается собой, а не пустой строкой', () => {
    // Пустая подпись в рейле неотличима от отсутствия пункта, поэтому ключ
    // виден на экране: так его замечают до того, как он уедет к потребителю.
    expect(translate('ru', 'nonexistent')).toBe('nonexistent');
});

test('неизвестный ключ на неизвестном языке тоже возвращается собой', () => {
    expect(translate('de', 'nonexistent')).toBe('nonexistent');
});
