import { expect, test } from '@playwright/test';
import { barHeightValue } from '../src/cross-service/barHeight';

/**
 * Значение переменной высоты плашки — прямыми вызовами.
 *
 * **Проверяется чистая часть, а не запись в документ.** Решение «какое значение
 * у переменной» вынесено из записи именно ради этого: браузер в наборах пакета
 * не поднимается ни одним набором, а само правило — арифметика по числу занявших
 * плашек и измеренной высоте.
 *
 * **Что остаётся браузерным сценариям продуктов.** Что плашка действительно
 * измеряется, что переменная доходит до оболочки и что содержимое получает
 * отступ, — это встраивание, и проверяется оно там, где живёт.
 */

test('занявшая плашка отдаёт измеренную высоту в пикселях', () => {
    expect(barHeightValue(1, 49)).toBe('49px');
});

test('дробная высота округляется вверх: отступ короче плашки прячет строку', () => {
    expect(barHeightValue(1, 48.4)).toBe('49px');
});

test('нулевая высота снимает переменную: так выглядит плашка, скрытая продуктом', () => {
    expect(barHeightValue(1, 0)).toBeNull();
});

test('отрицательная высота снимает переменную', () => {
    expect(barHeightValue(1, -12)).toBeNull();
});

test('без занявших плашек переменной нет независимо от последней высоты', () => {
    expect(barHeightValue(0, 49)).toBeNull();
});

test('пока одна из двух плашек занимает место, высота сохраняется', () => {
    expect(barHeightValue(1, 49)).toBe('49px');
});

test('освободившая последняя плашка снимает переменную', () => {
    expect(barHeightValue(0, 49)).toBeNull();
});

test('несостоявшееся измерение снимает переменную', () => {
    expect(barHeightValue(1, Number.NaN)).toBeNull();
    expect(barHeightValue(1, Number.POSITIVE_INFINITY)).toBeNull();
});
